
/*
 * feng_rao_basis_check.c
 *
 * Feng-Rao order-bound checker.
 *
 * Input:
 *   n k
 *   n*n integers: lead[i][j]
 *
 * lead[i][j]:
 *   -1 : zero product
 *    0..n-1 : index of leading basis element
 *
 * Basis indices must follow the chosen monomial order.
 *
 * Compile:
 *   gcc -O2 -Wall -Wextra -std=c11 \
 *       feng_rao_basis_check.c -o feng_rao
 *
 * Run:
 *   ./feng_rao multiplication.txt
 */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define MAX_N 4096

static int lead[MAX_N][MAX_N];
static int nu[MAX_N];

static int n;
static int k;

/*
 * One-way well-behaving pair.
 *
 * (i,j) is WB if every strictly smaller
 * pair (a,b), with a<=i and b<=j,
 * has a strictly smaller leading index.
 */
static int is_wb(int i, int j)
{
    int s = lead[i][j];

    if (s < 0)
        return 0;

    for (int a = 0; a <= i; a++) {
        for (int b = 0; b <= j; b++) {

            if (a == i && b == j)
                continue;

            int t = lead[a][b];

            if (t >= s)
                return 0;
        }
    }

    return 1;
}

/*
 * Calculate Feng-Rao numbers.
 *
 * nu[s] = number of indices i for which
 * there exists j such that (i,j) is WB
 * and lead[i][j] == s.
 *
 * A given i is counted only once.
 */
static void calculate_nu(void)
{
    memset(nu, 0, sizeof(nu));

    for (int i = 0; i < n; i++) {

        int counted[MAX_N] = {0};

        for (int j = 0; j < n; j++) {

            if (!is_wb(i, j))
                continue;

            int s = lead[i][j];

            if (s >= 0 && !counted[s]) {
                nu[s]++;
                counted[s] = 1;
            }
        }
    }
}

/*
 * Print WB pairs.
 */
static void print_wb_pairs(void)
{
    printf("\n=== WB pairs ===\n");

    for (int i = 0; i < n; i++) {
        for (int j = 0; j < n; j++) {

            if (is_wb(i, j)) {
                printf("(%d,%d) -> %d\n",
                       i, j, lead[i][j]);
            }
        }
    }
}

/*
 * Print Feng-Rao numbers.
 */
static void print_nu(void)
{
    printf("\n=== Feng-Rao numbers ===\n");

    for (int s = 0; s < n; s++) {
        printf("nu[%d] = %d\n", s, nu[s]);
    }
}

/*
 * Order-bound estimate.
 *
 * For the code generated by the first k
 * ordered basis elements:
 *
 * d >= min { nu[s] : s >= k }
 */
static void calculate_distance_bound(void)
{
    int d = -1;
    int argmin = -1;

    for (int s = k; s < n; s++) {

        if (d < 0 || nu[s] < d) {
            d = nu[s];
            argmin = s;
        }
    }

    printf("\n=== Feng-Rao distance bound ===\n");

    if (d < 0) {
        printf("No available indices.\n");
        return;
    }

    printf("Basis dimension k = %d\n", k);
    printf("Minimum nu       = %d\n", d);
    printf("Minimum index    = %d\n", argmin);
    printf("Distance bound   : d >= %d\n", d);
}

int main(int argc, char **argv)
{
    if (argc != 2) {
        fprintf(stderr,
                "Usage: %s multiplication.txt\n",
                argv[0]);
        return 1;
    }

    FILE *fp = fopen(argv[1], "r");

    if (!fp) {
        perror("fopen");
        return 1;
    }

    if (fscanf(fp, "%d%d", &n, &k) != 2) {
        fprintf(stderr, "Invalid header.\n");
        fclose(fp);
        return 1;
    }

    if (n <= 0 || n > MAX_N || k < 0 || k >= n) {
        fprintf(stderr, "Invalid n or k.\n");
        fclose(fp);
        return 1;
    }

    for (int i = 0; i < n; i++) {
        for (int j = 0; j < n; j++) {

            if (fscanf(fp, "%d", &lead[i][j]) != 1) {
                fprintf(stderr,
                        "Invalid multiplication table.\n");
                fclose(fp);
                return 1;
            }

            if (lead[i][j] < -1 ||
                lead[i][j] >= n) {
                fprintf(stderr,
                        "Invalid leading index at (%d,%d).\n",
                        i, j);
                fclose(fp);
                return 1;
            }
        }
    }

    fclose(fp);

    printf("Feng-Rao basis checker\n");
    printf("Number of basis elements: %d\n", n);

    calculate_nu();

    print_wb_pairs();
    print_nu();
    calculate_distance_bound();

    return 0;
}
